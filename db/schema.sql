-- Student Record System
-- Database Schema
-- PostgreSQL

BEGIN;

-- 1. Users: login credentials and role
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('Admin', 'Faculty', 'Student', 'Parent')),
    failed_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (failed_attempts >= 0),
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Students
CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(id),
    roll_no VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    dob DATE NOT NULL,
    department VARCHAR(100) NOT NULL,
    semester INTEGER NOT NULL CHECK (semester BETWEEN 1 AND 12),
    guardian_contact VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Faculty
CREATE TABLE IF NOT EXISTS faculty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL
);

-- 4. Courses
CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    semester INTEGER NOT NULL CHECK (semester BETWEEN 1 AND 12),
    faculty_id BIGINT REFERENCES faculty(id)
);

-- 5. Enrolments
CREATE TABLE IF NOT EXISTS enrolments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    course_id BIGINT NOT NULL REFERENCES courses(id),
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (student_id, course_id)
);

-- 6. Grades
CREATE TABLE IF NOT EXISTS grades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id BIGINT NOT NULL REFERENCES enrolments(id),
    marks NUMERIC(5,2) NOT NULL CHECK (marks BETWEEN 0 AND 100),
    letter_grade VARCHAR(2) NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES users(id),
    updated_reason TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (enrolment_id)
);

-- 7. Attendance records
CREATE TABLE IF NOT EXISTS attendance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id BIGINT NOT NULL REFERENCES enrolments(id),
    session_date DATE NOT NULL,
    status VARCHAR(10) NOT NULL
        CHECK (status IN ('Present', 'Absent', 'Late')),
    marked_by BIGINT NOT NULL REFERENCES users(id),
    marked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (enrolment_id, session_date)
);

-- 8. Grievances
CREATE TABLE IF NOT EXISTS grievances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    reference_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open', 'In Review', 'Resolved')),
    description TEXT NOT NULL,
    raised_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ
);

-- 9. Parent links
CREATE TABLE IF NOT EXISTS parent_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_user_id BIGINT NOT NULL REFERENCES users(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    UNIQUE (parent_user_id, student_id)
);

-- 10. Audit log
CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    action VARCHAR(50) NOT NULL,
    entity VARCHAR(100) NOT NULL,
    old_value JSONB,
    new_value JSONB,
    "timestamp" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Helpful indexes for common lookups
CREATE INDEX IF NOT EXISTS idx_students_name
    ON students(name);

CREATE INDEX IF NOT EXISTS idx_enrolments_course
    ON enrolments(course_id);

CREATE INDEX IF NOT EXISTS idx_grades_enrolment
    ON grades(enrolment_id);

CREATE INDEX IF NOT EXISTS idx_attendance_enrolment_date
    ON attendance_records(enrolment_id, session_date);

CREATE INDEX IF NOT EXISTS idx_grievances_student
    ON grievances(student_id);

CREATE INDEX IF NOT EXISTS idx_audit_log_timestamp
    ON audit_log("timestamp");

COMMIT;